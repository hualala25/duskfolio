#!/usr/bin/env python3
"""
Subset the site's fonts to the characters it can actually draw.

The fontsource packages ship their Chinese faces as ~100 unicode-range slices each (1259 files,
37 MB). A browser only downloads the slices whose range holds a character it is about to draw — but
the first screen needs 63 of them, and on a slow link those small requests fill every connection the
browser will open, so the engine's three.js waits behind them.

This builds the site's own faces instead: for each role, one file per weight, holding only the
characters the site's own text can reach (its profile, its documents, its interface). The result is a
handful of small files instead of a hundred — one request each, and a fraction of the bytes.

    python3 scripts/font-subset.py            # writes public/fonts/ and the @font-face CSS

The CSS it writes is what src/fonts reads: the faces are registered under the same family names the
page's font stacks use, with a unicode-range covering everything the site can draw.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONTS = ROOT / "node_modules" / "@fontsource"
OUT = ROOT / "public" / "fonts"
# the handwriting face is its own package (not under @fontsource)
LXGW = ROOT / "node_modules" / "lxgw-wenkai-webfont"

# the faces the site uses: the family the page's stack asks for, the file(s) to merge, the weight
FACES = [
    ("Noto Serif SC", ["noto-serif-sc/400", "noto-serif-sc/500", "noto-serif-sc/600"], "serif"),
    ("Noto Sans SC", ["noto-sans-sc/300", "noto-sans-sc/500"], "sans"),
    ("LXGW WenKai", ["lxgw-wenkai-webfont/lxgwwenkai-regular"], "hand"),
    # the Japanese faces: the English edition's serif and sans, and the handwriting
    ("Shippori Mincho", ["shippori-mincho/400", "shippori-mincho/500", "shippori-mincho/600"], "serif-ja"),
    ("Zen Kaku Gothic New", ["zen-kaku-gothic-new/400", "zen-kaku-gothic-new/500"], "sans-ja"),
    ("Klee One", ["klee-one/600"], "hand-ja"),
]


def site_characters() -> set[str]:
    """every character the site can draw: its profile, its documents, its interface"""
    chars: set[str] = set()
    for pat in ("profile/*.ts", "profile/documents/*.ts", "src/**/*.ts", "src/**/*.tsx", "index.html"):
        for f in ROOT.glob(pat):
            try:
                t = f.read_text(encoding="utf-8")
            except Exception:
                continue
            for ch in t:
                if ord(ch) > 0x2000:
                    chars.add(ch)
    return chars


def parse_ranges(spec: str) -> list[tuple[int, int]]:
    out = []
    for part in spec.split(","):
        part = part.strip().upper()
        if not part.startswith("U+"):
            continue
        body = part[2:]
        try:
            if "-" in body:
                a, b = body.split("-", 1)
                out.append((int(a, 16), int(b, 16)))
            else:
                v = int(body, 16)
                out.append((v, v))
        except ValueError:
            pass
    return out


def collect_face_slices(pkg: str, css_name: str) -> list[tuple[pathlib.Path, list[tuple[int, int]]]]:
    """the slices of one fontsource CSS: the file and the ranges it holds"""
    base = LXGW if pkg == "lxgw-wenkai-webfont" else FONTS / pkg
    css = base / f"{css_name}.css"
    if not css.exists():
        return []
    text = css.read_text(encoding="utf-8")
    out = []
    for m in re.finditer(
        r"@font-face\s*\{[^}]*?src:\s*url\(['\"]?\./?files/([^'\")]+?)['\"]?\)[^}]*?unicode-range:\s*([^;]+);",
        text,
        re.S,
    ):
        name, spec = m.group(1), m.group(2)
        path = base / "files" / name
        if path.exists():
            out.append((path, parse_ranges(spec)))
    return out


def main() -> int:
    try:
        from fontTools import subset
        from fontTools.ttLib import TTFont
    except ImportError:
        print("需要 fontTools 与 brotli：pip3 install --user fonttools brotli")
        return 1

    chars = site_characters()
    print(f"站点可能显示的字符：{len(chars)} 个")

    OUT.mkdir(parents=True, exist_ok=True)
    css_out = [
        "/*",
        " * The site's own faces — generated by scripts/font-subset.py.",
        " *",
        " * The fontsource packages ship their Chinese faces as a hundred unicode-range slices each.",
        " * A browser asks for the slices it needs, but the first screen needed sixty-three of them,",
        " * and on a slow link those small requests filled every connection the browser would open —",
        " * so the engine's three.js waited behind them.",
        " *",
        " * These are the same faces, subset to the characters this site can draw: one file a weight,",
        " * one request, a fraction of the bytes.",
        " *",
        " * Regenerate: python3 scripts/font-subset.py",
        " */",
    ]

    total = 0
    for family, sources, role in FACES:
        for src in sources:
            pkg, css_name = src.rsplit("/", 1)
            slices = collect_face_slices(pkg, css_name)
            if not slices:
                continue

            # the slices that hold a character the site can draw
            need = []
            for path, ranges in slices:
                for ch in chars:
                    cp = ord(ch)
                    if any(a <= cp <= b for a, b in ranges):
                        need.append(path)
                        break
            if not need:
                continue

            wm = re.search(r"(\d+)$", css_name) or re.search(r"-(\d+)$", css_name)
            weight = wm.group(1) if wm else "400"
            out_name = f"{pkg.replace('/', '-')}-{weight}.woff2"
            out_path = OUT / out_name

            # merge the slices into one font, then subset it
            merged = OUT / f".merged-{pkg.replace('/', '-')}-{weight}.ttf"
            merged.parent.mkdir(parents=True, exist_ok=True)
            try:
                from fontTools.merge import Merger

                merger = Merger()
                merged_font = merger.merge([str(p) for p in need])
                merged_font.save(str(merged))
                merged_font.close()
            except Exception as e:
                print(f"  {pkg} {weight}: 合并失败（{e}），改用单片")
                merged = need[0]

            # subset it to the site's characters
            options = subset.Options()
            options.flavor = "woff2"
            options.desubroutinize = True
            options.layout_features = ["*"]
            options.name_IDs = ["*"]
            options.notdef_outline = True
            options.drop_tables = []
            font = subset.load_font(str(merged), options)
            subsetter = subset.Subsetter(options=options)
            subsetter.populate(text="".join(chars))
            subsetter.subset(font)
            subset.save_font(font, str(out_path), options)
            font.close()
            if merged != need[0] and merged.exists():
                merged.unlink()

            size = out_path.stat().st_size
            total += size
            print(f"  {family} {weight}: {len(need)} 片 → 1 个 {size // 1024} KB  ({out_name})")

            # the @font-face: the whole site's characters in one range
            css_out += [
                "@font-face {",
                f"  font-family: '{family}';",
                "  font-style: normal;",
                f"  font-weight: {weight};",
                "  font-display: swap;",
                f'  src: url(./fonts/{out_name}) format("woff2");',
                "  unicode-range: U+2000-2FFFF;",
                "}",
            ]

    (ROOT / "public" / "fonts.css").write_text("\n".join(css_out) + "\n", encoding="utf-8")
    print(f"\n合计 {total // 1024} KB，CSS 写入 public/fonts.css")
    return 0


if __name__ == "__main__":
    sys.exit(main())
